function setLang(l) {
  currentLang = STR[l] ? l : 'zh';
}
function getLang() {
  return currentLang;
}
function t(key) {
  const dict = STR[currentLang] || STR.zh;
  let s = dict[key];
  if (s === undefined) s = STR.zh[key];
  if (s === undefined) return key;
  for (let i = 1; i < arguments.length; i++) {
    s = s.split('{' + (i - 1) + '}').join(String(arguments[i]));
  }
  return s;
}
